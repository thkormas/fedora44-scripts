#!/bin/bash
# =====================================================================
# SCRIPT ΑΝΑΒΑΘΜΙΣΗΣ SLACKWARE 15.0 STABLE ΣΕ SLACKWARE-CURRENT (MULTILIB)
# =====================================================================
# ΟΔΗΓΙΕΣ:
# 1. Εκτελέστε το ΜΟΝΟ ως root.
# 2. Εκτελέστε το από καθαρή κονσόλα (tty) και ΟΧΙ μέσα από το KDE/Xfce.
# 3. Κρατήστε backup των αρχείων σας πριν ξεκινήσετε!
# =====================================================================

# Σύστημα ελέγχου σφαλμάτων
check_status() {
  if [ $? -ne 0 ]; then
    echo ""
    echo "❌ ΣΦΑΛΜΑ: Το προηγούμενο βήμα απέτυχε! Η διαδικασία διακόπηκε για ασφάλεια."
    echo "Διορθώστε το πρόβλημα και τρέξτε ξανά το script."
    exit 1
  fi
}

# 1. Έλεγχος αν ο χρήστης είναι root
if [ "$EUID" -ne 0 ]; then
  echo "❌ Παρακαλώ τρέξτε το script ως root (su -)."
  exit 1
fi

# 2. Έλεγχος αν τρέχει μέσα από γραφικό περιβάλλον (X11 / Wayland)
if [ -n "$DISPLAY" ] || [ -n "$WAYLAND_DISPLAY" ]; then
  echo "❌ ΣΦΑΛΜΑ: Ανιχνεύθηκε ενεργό γραφικό περιβάλλον (KDE/Xfce/κλπ)."
  echo "Η αναβάθμιση σε Current μπορεί να κρασάρει τον X server και να καταστρέψει το σύστημα."
  echo "Παρακαλώ βγείτε σε καθαρή κονσόλα (Ctrl+Alt+F1), κάντε login ως root και τρέξτε το από εκεί."
  exit 1
fi

echo "====================================================================="
echo "Ξεκινάει η διαδικασία αναβάθμισης σε Slackware-Current (MULTILIB)."
echo "Το script θα σταματάει σε κάθε βήμα για να διαβάζετε την επεξήγηση."
echo "====================================================================="
echo ""

# 3. Έλεγχος και αυτόματη εγκατάσταση του lftp αν λείπει
if ! command -v lftp &> /dev/null; then
    echo "🔍 Το εργαλείο lftp λείπει. Εγκατάσταση μέσω slackpkg..."
    slackpkg install lftp
    check_status
fi

# ---------------------------------------------------------------------
# ΒΗΜΑ 1: Χειροκίνητη αλλαγή των Mirrors
# ---------------------------------------------------------------------
echo "[ΒΗΜΑ 1]: Αλλαγή των καθρεφτών (Mirrors) σε Current"
echo "Επεξήγηση: Θα ανοίξει το αρχείο ρυθμίσεων των mirrors."
echo "Πρέπει να βάλετε ένα '#' μπροστά από το mirror του Slackware 15.0"
echo "και να βγάλετε το '#' από ΕΝΑΝ καθρέφτη του slackware64-current."
echo "Μόλις τελειώσετε, αποθηκεύστε (Ctrl+O, Enter, Ctrl+X)."
echo "---------------------------------------------------------------------"
read -p "Πατήστε [Enter] για να ανοίξει το αρχείο ρυθμίσεων..."

nano /etc/slackpkg/mirrors
check_status

echo ""
echo "Το Βήμα 1 ολοκληρώθηκε."
echo "====================================================================="
echo ""

# ---------------------------------------------------------------------
# ΒΗΜΑ 2: Λήψη των νέων λιστών πακέτων & Αναβάθμιση του slackpkg
# ---------------------------------------------------------------------
echo "[ΒΗΜΑ 2]: Ενημέρωση λιστών και του ίδιου του slackpkg"
echo "Επεξήγηση: Λήψη των νέων GPG κλειδιών και λιστών του Current."
echo "---------------------------------------------------------------------"
read -p "Πατήστε [Enter] για να εκτελέσετε το Βήμα 2..."

slackpkg update gpg && slackpkg update
check_status

slackpkg upgrade slackpkg
check_status

echo ""
echo "Το Βήμα 2 ολοκληρώθηκε."
echo "====================================================================="
echo ""

# ---------------------------------------------------------------------
# ΒΗΜΑ 3: ΠΡΟ-ΑΝΑΒΑΘΜΙΣΗ MULTILIB (Κρίσιμο)
# ---------------------------------------------------------------------
echo "[ΒΗΜΑ 3]: Προετοιμασία και αναβάθμιση των Multilib εργαλείων"
echo "Επεξήγηση: Πριν την glibc, πρέπει να κατεβάσουμε τα νέα multilib πακέτα"
echo "από το αποθετήριο του Alien Pasture για το Current, ώστε να μην κρασάρει το σύστημα."
echo "---------------------------------------------------------------------"
read -p "Πατήστε [Enter] για να γίνει λήψη των Current Multilib πακέτων..."

# Δημιουργία προσωρινού φακέλου για τα multilib
mkdir -p /tmp/multilib_current && cd /tmp/multilib_current
check_status

echo "Κατέβασμα των νέων πακέτων glibc-solibs και γύρω βιβλιοθηκών..."
lftp -c "open http://slackware.com; mirror -j -i 'aaa_glibc-solibs|gcc|glibc'"
check_status

echo "Εγκατάσταση των νέων multilib βιβλιοθηκών..."
upgradepkg --install-new *.txz
check_status

cd - > /dev/null

echo ""
echo "Το Βήμα 3 ολοκληρώθηκε επιτυχώς."
echo "====================================================================="
echo ""

# ---------------------------------------------------------------------
# ΒΗΜΑ 4: Εγκατάσταση νέων πακέτων
# ---------------------------------------------------------------------
echo "[ΒΗΜΑ 4]: Εγκατάσταση των νέων πακέτων του Current"
echo "Επεξήγηση: Θα εμφανιστεί μια λίστα με νέα προγράμματα του Current."
echo "Αφήστε τα όλα επιλεγμένα και πατήστε OK."
echo "---------------------------------------------------------------------"
read -p "Πατήστε [Enter] για να εκτελέσετε το Βήμα 4..."

slackpkg install-new
check_status

echo ""
echo "Το Βήμα 4 ολοκληρώθηκε."
echo "====================================================================="
echo ""

# ---------------------------------------------------------------------
# ΒΗΜΑ 5: Η μεγάλη αναβάθμιση συστήματος
# ---------------------------------------------------------------------
echo "[ΒΗΜΑ 5]: Συνολική αναβάθμιση (Upgrade All)"
echo "Επεξήγηση: Αυτό θα αναβαθμίσει όλα τα επίσημα πακέτα σας."
echo "---------------------------------------------------------------------"
read -p "Πατήστε [Enter] για να ξεκινήσει η μεγάλη αναβάθμιση..."

slackpkg upgrade-all
check_status

echo ""
echo "Το Βήμα 5 ολοκληρώθηκε."
echo "====================================================================="
echo ""

# ---------------------------------------------------------------------
# ΒΗΜΑ 6: ΕΠΑΝΕΓΚΑΤΑΣΤΑΣΗ ΠΛΗΡΟΥΣ MULTILIB
# ---------------------------------------------------------------------
echo "[ΒΗΜΑ 6]: Πλήρης συγχρονισμός Multilib για το Current"
echo "Επεξήγηση: Τώρα που μπήκε το Current, θα ξαναπεράσουμε όλα τα multilib"
echo "πακέτα για να είμαστε σίγουροι ότι το Steam/Wine/Nvidia θα δουλεύουν άψογα."
echo "---------------------------------------------------------------------"
read -p "Πατήστε [Enter] για λήψη και εγκατάσταση του πλήρους multilib..."

cd /tmp/multilib_current
# Καθαρίζουμε τα παλιά αρχεία πριν το νέο κατέβασμα
rm -f *.txz
lftp -c "open http://slackware.com; mirror -j"
check_status

upgradepkg --install-new *.txz
check_status
cd - > /dev/null

echo ""
echo "Το Βήμα 6 ολοκληρώθηκε."
echo "====================================================================="
echo ""

# ---------------------------------------------------------------------
# ΒΗΜΑ 7: Καθαρισμός συστήματος
# ---------------------------------------------------------------------
echo "[ΒΗΜΑ 7]: Αφαίρεση παλιών/καταργημένων πακέτων"
echo "Επεξήγηση: Αφαιρεί πακέτα που καταργήθηκαν. ΠΡΟΣΟΧΗ: Ξε-επιλέξτε"
echo "τα δικά σας πακέτα (π.χ. από SBo) καθώς και τα multilib αν εμφανιστούν!"
echo "---------------------------------------------------------------------"
read -p "Πατήστε [Enter] για να εκτελέσετε το Βήμα 7..."

slackpkg clean-system
check_status

echo ""
echo "Το Βήμα 7 ολοκληρώθηκε."
echo "====================================================================="
echo ""

# ---------------------------------------------------------------------
# ΒΗΜΑ 8: Δημιουργία Initrd (Κρίσιμο για Generic Kernels)
# ---------------------------------------------------------------------
echo "[ΒΗΜΑ 8]: Έλεγχος και δημιουργία Initrd"
echo "Επεξήγηση: Παραγωγή νέου RAM disk για τον νέο πυρήνα."
echo "---------------------------------------------------------------------"
read -p "Πατήστε [Enter] για να δείτε/τρέξετε την προτεινόμενη εντολή mkinitrd..."

if [ -f /usr/share/mkinitrd/mkinitrd_command_generator.sh ]; then
    echo "Προτεινόμενη εντολή για το σύστημά σας:"
    CMD=$(/usr/share/mkinitrd/mkinitrd_command_generator.sh | grep "mkinitrd -c")
    echo "$CMD"
    echo "---------------------------------------------------------------------"
    read -p "Θέλετε να εκτελεστεί αυτόματα αυτή η εντολή; (y/n): " gen_initrd
    if [ "$gen_initrd" = "y" ] || [ "$gen_initrd" = "Y" ]; then
        eval $CMD
        check_status
        echo "Το Initrd δημιουργήθηκε!"
    else
        echo "Παράκαμψη initrd. Βεβαιωθείτε ότι χρησιμοποιείτε Huge πυρήνα!"
    fi
else
    echo "Το εργαλείο mkinitrd δεν βρέθηκε. Αν έχετε huge πυρήνα, προχωρήστε."
fi

echo ""
echo "Το Βήμα 8 ολοκληρώθηκε."
echo "====================================================================="
echo ""

# ---------------------------------------------------------------------
# ΒΗΜΑ 9: Ενημέρωση ή Εγκατάσταση του Bootloader
# ---------------------------------------------------------------------
echo "[ΒΗΜΑ 9]: Ενημέρωση ή Εγκατάσταση του Bootloader"
echo "Επεξήγηση: Δείτε τη δομή των δίσκων σας παρακάτω για να επιλέξετε σωστά."
echo "---------------------------------------------------------------------"
echo "📊 ΤΡΕΧΟΥΣΑ ΔΟΜΗ ΔΙΣΚΩΝ ΚΑΙ PARTITIONS (lsblk):"
lsblk
echo "---------------------------------------------------------------------"
echo "Επιλέξτε τον bootloader του συστήματός σας:"

select opt in "ELILO" "GRUB" "LILO" "Έξοδος χωρίς ενημέρωση (Επικίνδυνο)"; do
    case $opt in
        "ELILO")
            if ! command -v elilo >/dev/null 2>&1; then
                echo "❌ Το elilo δεν βρέθηκε σε αυτό το σύστημα (μάλλον δεν χρησιμοποιείτε ELILO)."
                echo "Επιστροφή στο μενού — δεν άλλαξε τίποτα."
                continue
            fi
            if [ ! -f /etc/elilo.conf ]; then
                echo "❌ Δεν βρέθηκε το /etc/elilo.conf. Επιστροφή στο μενού."
                continue
            fi
            echo "Εκτέλεση: elilo -v"
            elilo -v
            check_status
            echo "✅ Ο ELILO ενημερώθηκε."
            break
            ;;
        "GRUB")
            echo "---------------------------------------------------------------------"
            echo "Επιλέξατε GRUB. Τι θέλετε να κάνετε;"
            echo "1) Μόνο ενημέρωση μενού (grub-mkconfig) - [Συνιστώμενο αν είχατε ήδη GRUB]"
            echo "2) Πλήρης εγκατάσταση του GRUB στον δίσκο (grub-install)"
            echo "---------------------------------------------------------------------"
            read -r -p "Επιλογή (1 ή 2): " grub_action

            case $grub_action in
                1)
                    if ! command -v grub-mkconfig >/dev/null 2>&1; then
                        echo "❌ Το grub-mkconfig δεν βρέθηκε. Επιστροφή στο μενού."
                        continue
                    fi
                    echo "Εκτέλεση: grub-mkconfig -o /boot/grub/grub.cfg"
                    grub-mkconfig -o /boot/grub/grub.cfg
                    check_status
                    echo "✅ Το μενού του GRUB ενημερώθηκε."
                    break
                    ;;
                2)
                    echo "⚠️  ΠΡΟΣΟΧΗ: Λάθος συσκευή = σύστημα που δεν ξεκινάει."
                    echo "Διαθέσιμοι δίσκοι:"
                    lsblk -d -o NAME,SIZE,MODEL
                    read -r -p "Συσκευή εγκατάστασης (π.χ. /dev/sda) ή [Enter] για επιστροφή: " grub_dev
                    if [ -z "$grub_dev" ]; then
                        echo "Επιστροφή στο μενού."
                        continue
                    fi
                    if [ ! -b "$grub_dev" ]; then
                        echo "❌ Το '$grub_dev' δεν είναι block device. Επιστροφή στο μενού."
                        continue
                    fi
                    if [ -d /sys/firmware/efi ]; then
                        echo "Ανιχνεύθηκε UEFI."
                        if ! mountpoint -q /boot/efi; then
                            echo "❌ Το /boot/efi δεν είναι προσαρτημένο. Προσαρτήστε το πρώτα και ξανατρέξτε:"
                            echo "   mount /dev/<efi-partition> /boot/efi"
                            continue
                        fi
                        echo "Εκτέλεση: grub-install --target=x86_64-efi --efi-directory=/boot/efi --bootloader-id=Slackware --recheck $grub_dev"
                        grub-install --target=x86_64-efi --efi-directory=/boot/efi --bootloader-id=Slackware --recheck "$grub_dev"
                    else
                        echo "Ανιχνεύθηκε BIOS/Legacy."
                        echo "Εκτέλεση: grub-install --target=i386-pc --recheck $grub_dev"
                        grub-install --target=i386-pc --recheck "$grub_dev"
                    fi
                    check_status
                    echo "Ενημέρωση μενού: grub-mkconfig -o /boot/grub/grub.cfg"
                    grub-mkconfig -o /boot/grub/grub.cfg
                    check_status
                    echo "✅ Ο GRUB εγκαταστάθηκε και το μενού ενημερώθηκε."
                    break
                    ;;
                *)
                    echo "❗ Μη έγκυρη επιλογή (δώστε 1 ή 2). Επιστροφή στο μενού."
                    continue
                    ;;
            esac
            ;;
        "LILO")
            if ! command -v lilo >/dev/null 2>&1; then
                echo "❌ Το lilo δεν βρέθηκε σε αυτό το σύστημα. Επιστροφή στο μενού."
                continue
            fi
            if [ ! -f /etc/lilo.conf ]; then
                echo "❌ Δεν βρέθηκε το /etc/lilo.conf. Επιστροφή στο μενού."
                continue
            fi
            echo "Εκτέλεση: lilo -v"
            lilo -v
            check_status
            echo "✅ Ο LILO ενημερώθηκε."
            break
            ;;
        "Έξοδος χωρίς ενημέρωση (Επικίνδυνο)")
            echo ""
            echo "⚠️  Βγήκατε ΧΩΡΙΣ ενημέρωση bootloader."
            echo "Αν έγινε αναβάθμιση πυρήνα, το σύστημα μπορεί να ΜΗΝ ξεκινήσει."
            echo "Τρέξτε χειροκίνητα την κατάλληλη εντολή (elilo / grub-mkconfig -o /boot/grub/grub.cfg / lilo -v)"
            echo "πριν κάνετε reboot."
            exit 0
            ;;
        *)
            echo "❗ Μη έγκυρη επιλογή — δώστε αριθμό 1, 2, 3 ή 4."
            continue
            ;;
    esac
done

echo ""
echo "Το Βήμα 9 ολοκληρώθηκε."
echo "====================================================================="
echo ""
echo "✅ Η διαδικασία αναβάθμισης σε Slackware-Current ολοκληρώθηκε."
echo ""
echo "ΕΠΟΜΕΝΑ ΒΗΜΑΤΑ — ΜΗΝ ΤΑ ΠΑΡΑΛΕΙΨΕΤΕ:"
echo "  1. Ελέγξτε τα αρχεία *.new στο /etc (fstab, inittab, rc.d/*, lilo.conf,"
echo "     slackpkg/mirrors) και συγχωνεύστε ό,τι χρειάζεται."
echo "  2. Ελέγξτε ότι το /etc/slackpkg/mirrors δείχνει ΜΟΝΟ σε current mirrors."
echo "  3. Κάντε reboot:   reboot"
echo "  4. Μετά το reboot επιβεβαιώστε:  uname -r  και  cat /etc/slackware-version"
echo "  5. Αν χρειάζεστε 32-bit (Steam/Wine), προσθέστε τα compat32 πακέτα"
echo "     του Alien Bob για current (τα multilib gcc/glibc δεν χρειάζονται πλέον)."
echo "====================================================================="
